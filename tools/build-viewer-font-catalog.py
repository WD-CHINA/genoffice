#!/usr/bin/env python3
"""Generate portable PPT font faces from the migrated Word CSS and manifests.

uv run --with fonttools --with brotli python tools/build-viewer-font-catalog.py
WOFF2 advance/coverage sidecars keep layout workers free of Node/Brotli APIs.
Browser width feedback still supplies shaped/kerning widths from the original font.
"""
import hashlib
import json
import re
from pathlib import Path
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / 'apps/viewer/src/web'
FONTS = ROOT / 'packages/viewer-renderers/src/docs/renderer/fonts'

ALIASES = {
    'Carlito GO': ['Carlito', 'Calibri'], 'Caladea': ['Cambria'],
    'Liberation Sans': ['Arial', 'Helvetica', 'Helvetica Neue'],
    'Liberation Serif': ['Times New Roman', 'Times'], 'Liberation Mono': ['Courier New', 'Courier'],
    'Aptos GO': ['Aptos'], 'Aptos Display GO': ['Aptos Display'], 'Aptos Narrow GO': ['Aptos Narrow'],
    'Noto Sans CJK SC': ['Microsoft YaHei', '微软雅黑', 'SimHei', '黑体', 'DengXian', '等线'],
    'Noto Serif CJK SC': ['SimSun', '宋体'], 'Noto Naskh Arabic': ['Geeza Pro'],
    'Noto Sans Arabic': ['Tahoma', 'Arabic'],
    'GenOffice Sans KR': ['Malgun Gothic', '맑은 고딕', 'Gulim', 'Dotum'],
    'GenOffice Serif KR': ['Batang', '바탕', 'Gungsuh', 'NanumMyeongjo', 'Nanum Myeongjo'],
    'GenOffice Gothic KR': ['NanumGothic', 'Nanum Gothic', 'NanumGothic ExtraBold'],
    'GenOffice Che Latin KR': ['BatangChe', 'GulimChe', 'DotumChe', 'GungsuhChe'],
    'GenOffice Poppins': ['Poppins'], 'GenOffice DM Sans': ['DM Sans'],
    'GenOffice Cordia': ['Cordia New', 'CordiaUPC'],
    'GenOffice Sarabun': ['Sarabun', 'TH Sarabun New', 'TH SarabunPSK'],
    'GenOffice Tamil': ['Latha', 'Nirmala UI Tamil'],
    'GenOffice Bengali': ['Nirmala UI', 'Nirmala UI Bengali'],
    'Noto Naskh Arabic SA': ['Simplified Arabic'],
    'Noto Naskh Arabic TA': ['Traditional Arabic'],
    'GenOffice UI Kana JP': [],
    'GenOffice Symbol': ['Symbol'], 'GenOffice Wingdings': ['Wingdings'],
    'GenOffice Wingdings 2': ['Wingdings 2'], 'GenOffice Wingdings 3': ['Wingdings 3'],
    'GenOffice Webdings': ['Webdings'], 'GenOffice Symbols': ['Segoe UI Symbol'],
}


def main():
    aliases = {k: list(v) for k, v in ALIASES.items()}
    for path in sorted((ROOT / 'packages/font-metrics/measurements/families').glob('*.json')):
        manifest = json.loads(path.read_text())
        names = manifest.get('standsInFor', [])
        if isinstance(names, str):
            names = [names]
        aliases.setdefault(manifest['family'], []).extend(names)
    # @import generated precedes the hand-written faces, matching the browser cascade.
    css = '\n'.join((FONTS / n).read_text() for n in ['fonts.generated.css', 'fonts.css'])
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    sources, entries = {}, []
    descriptors = {'unicode-range': 'unicodeRange', 'size-adjust': 'sizeAdjust',
                   'ascent-override': 'ascentOverride', 'descent-override': 'descentOverride',
                   'line-gap-override': 'lineGapOverride'}
    for block in re.findall(r'@font-face\s*\{([^}]+)\}', css):
        props = dict((k.strip(), v.strip()) for k, v in re.findall(r'([\w-]+)\s*:\s*([^;]+);', block))
        url = re.search(r"url\(['\"]?([^)'\"]+)", props.get('src', ''))
        if not url:
            continue  # local() faces cannot be shipped in a static viewer
        source = url[1]
        path = ROOT / ('packages/ui/src/fonts/' + Path(source).name) if source.startswith('@genoffice/ui/') else FONTS / source
        family = props['font-family'].strip("'\"")
        # Most upstream metric aliases carry their declared Office name plus GO;
        # manifests supply exceptional/multiple names, the table adds script faces.
        if family.endswith(' GO'):
            aliases.setdefault(family, []).append(family[:-3])
        sources[str(path)] = source
        entries.append({'family': family, 'names': list(dict.fromkeys([family, *aliases.get(family, [])])),
                        'bold': props.get('font-weight') == 'bold', 'italic': props.get('font-style') == 'italic',
                        'path': str(path), 'descriptors': {v: props[k] for k, v in descriptors.items() if k in props},
                        **({'tuneWin': True} if family == 'Carlito GO' else {})})
    for name in ['Symbol', 'Wingdings', 'Wingdings 2', 'Wingdings 3', 'Webdings', 'Symbols']:
        family = 'GenOffice ' + name
        path = WEB / 'fonts' / ('GenOffice' + name.replace(' ', '') + '-Regular.ttf')
        sources[str(path)] = str(path)
        entries.append({'family': family, 'names': [family, *aliases[family]], 'bold': False,
                        'italic': False, 'path': str(path), 'descriptors': {}})
    output = ['// Generated by tools/build-viewer-font-catalog.py; do not edit.',
              "import type { MetricFont } from './metric-font-types'"]
    metadata_dir = WEB / 'fonts/metrics'
    metadata_dir.mkdir(exist_ok=True)
    for i, path in enumerate(sources):
        path = Path(path)
        if not path.exists():
            raise ValueError(f'Missing font: {path}')
        if path.is_relative_to(FONTS):
            url = '@genoffice/viewer-renderers/docs/renderer/fonts/' + path.name
        elif path.is_relative_to(WEB):
            url = './fonts/' + path.name
        else:
            url = '@genoffice/ui/fonts/' + path.name
        output.append(f'import font{i} from {json.dumps(url + "?url")}')
        if path.suffix == '.woff2':
            font = TTFont(path)
            cmap = font.getBestCmap()
            # Glyph IDs distinguish present zero-advance marks from missing characters.
            advances = [[cp, font.getGlyphID(g), font['hmtx'][g][0]] for cp, g in sorted(cmap.items())]
            data = {'sourceSha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                    'unitsPerEm': font['head'].unitsPerEm, 'ascender': font['hhea'].ascent,
                    'descender': font['hhea'].descent, 'lineGap': font['hhea'].lineGap, 'advances': advances}
            (metadata_dir / (path.stem + '.json')).write_text(json.dumps(data, separators=(',', ':')) + '\n')
            output.append(f'import metrics{i} from "./fonts/metrics/{path.stem}.json?url"')
    output.extend(['', 'export const METRIC_FONTS: MetricFont[] = ['])
    indexes = {path: i for i, path in enumerate(sources)}
    catalog = []
    for i, entry in enumerate(entries):
        catalog.append({**entry, 'path': str(Path(entry['path']).relative_to(ROOT)), 'id': f'bundled:{i}'})
        index = indexes[entry.pop('path')]
        entry['id'] = f'bundled:{i}'
        raw = json.dumps(entry, ensure_ascii=False, separators=(',', ':'))[:-1]
        raw += f',"url":font{index}'
        if Path(list(sources)[index]).suffix == '.woff2':
            raw += f',"metricsUrl":metrics{index}'
        output.append('  ' + raw + '},')
    output.extend([']', ''])
    (WEB / 'metric-fonts.generated.ts').write_text('\n'.join(output))
    (WEB / 'fonts/catalog.json').write_text(json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + '\n')
    inputs = [Path(__file__), FONTS / 'fonts.css', FONTS / 'fonts.generated.css',
              *sorted((ROOT / 'packages/font-metrics/measurements/families').glob('*.json'))]
    provenance = {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest() for path in inputs}
    (WEB / 'fonts/catalog-provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
    print(f'{len(entries)} portable faces, {len(sources)} source files, {len(set(e["family"] for e in entries))} families')


if __name__ == '__main__':
    main()
